/* content/echo.js — ЭХО ⟲ (Ярус 2, v0.15.0).
   Твоё лучшее число возвращается само: D растёт постоянной скоростью, НО за это ΔT медленнее.
   Либо эхо, либо скорость — так механика требует выбора, а не просто «ещё бонус». */
(function (G) {
  'use strict';

  G.content = G.content || {};

  G.content.echo = {
    id: 'echo',

    cost: 12,             /* Δ — разовая покупка, открывает переключатель */

    /* скорость эха: D в секунду = min(ratePerSec · bestD, maxShare · обычный рост) */
    ratePerSec: 0.0015,
    maxShare: 0.5,        /* не больше половины обычного роста */

    /* цена включённого эха — ΔT медленнее */
    dtMult: 1.15,

    hint: 'Эхо возвращает твоё лучшее число: пока включено, D растёт сам, но ΔT становится медленнее. ' +
      'Скорость эха = min(0.0015·лучшее D, половина обычного роста) — на старте это очень много, ' +
      'в глубоком забеге меньше. Включил эхо — поезд скорости ушёл: либо одно, либо другое.'
  };
})(window.G = window.G || {});
