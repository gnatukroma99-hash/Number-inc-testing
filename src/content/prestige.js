/* content/prestige.js — данные первого перерождения (P1).
   ◆ Ядра — мета-ресурс: не сбрасываются никогда и дают постоянный множитель к M. */
(function (G) {
  'use strict';

  G.content = G.content || {};
  G.content.prestige = {
    id: 'p1',
    name: 'Перерождение P1',
    minD: 10,
    /* сколько ◆ даёт текущий D: floor(((D − minD) / 4)^0.75) */
    /* ◆ = ((D − minD) / 3.2)^0.85, ×(1 + 0.02·перерождений).
       v0.11.0: показатель 0.75 → 0.85 и делитель 4 → 3.2 — ядер в 1.5–2 раза больше,
       чтобы дерево прокачивалось за меньшее число перерождений. */
    gainFormula: 'floor(pow(max(0, D - minD) / 3.2, 0.85) * (1 + 0.02 * runs))',
    /* постоянный множитель к M от ядер.
       сессия №47: было '1.5 ** cores' — при ~1700 ◆ множитель упирался в предохранитель 1e300,
       и остальные M-множители становились невидимы. Теперь степень сжата корнем:
       1 ◆ = ×1.5, 10 ◆ = ×2.77, 100 ◆ = ×12.9, 1700 ◆ = ×2823, 1e6 ◆ ≈ ×1.7e44. */
    coreMultFormula: 'pow(1.5, pow(cores, 0.4))',
    resetScopes: ['run'],
    /* стартовые цифры после перерождения — узлы дерева ◆ (данные).
       vars: имя переменной -> id узла; formula считает цифры старта. */
    start: {
      vars: { lvl: 'tree_headstart', lvl2: 'tree_headstart2', lvl3: 'tree_headstart3' },
      formula: '2 * lvl + 10 * lvl2 + 40 * lvl3'
    },
    keepHint: 'Остаются: ◆ Ядра, ❖ ПРАЙМ, авто-апгрейды (scope meta), дерево ◆, рекорды.',
    resetHint: 'Сбрасываются: N, ⌁, все раундовые апгрейды, магазин и данные механик.'
  };
})(window.G = window.G || {});
