/* content/combo.js — КОМБО ⌘ (v0.20.0). Активная механика «здесь и сейчас»:
   быстро тапаешь по главному числу — копится серия, серия даёт временный множитель к M.
   Перестал тапать — серия гаснет сама. Это буквально «чем заняться руками». */
(function (G) {
  'use strict';

  G.content = G.content || {};

  G.content.combo = {
    id: 'combo',

    tapGain: 0.08,      /* сколько серии даёт один тап */
    maxCombo: 12,       /* предел серии */
    multPer: 0.06,      /* +6 % к M за каждую единицу серии (12 → ×1.72) */
    decayPerSec: 0.55,  /* как быстро гаснет серия */
    coolDown: 0.05,     /* антиавтоклик: чаще чем раз в 50 мс тапы не считаются */

    hint: 'Тапай по главному числу: каждый тап копит серию до 12, и серия даёт до +72 % к M. ' +
      'Стоит перестать — серия гаснет за пару секунд. Держи её в моменты, когда рядом искра, ' +
      'разлом или джекпот: множители складываются.'
  };
})(window.G = window.G || {});
